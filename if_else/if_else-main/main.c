//Дано целое число. Если оно является положительным, то прибавить к нему 1; в противном случае вычесть из него 2. Вывести полученное число.
#include <stdio.h>
int main(){
int x;
    scanf("%d", &x);
    if ( x > 0) {
        x = x + 1;
    }
   else {
       x  = x - 2;
   }
    printf("%d", x);
    return 0;
    
}






