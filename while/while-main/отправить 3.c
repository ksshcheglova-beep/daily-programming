/*Даны положительные числа 
A и B (A<B). На отрезке длины A размещено максимально возможное количество отрезков длины B (без наложений). Не используя операции умножения и деления, найти длину незанятой части отрезка A.*/
#include <stdio.h>

int main() {
    double a, b;
   
    scanf("%lf%lf", &a, &b);
    while (a >= b) {
        a = a - b;
    }
    printf("%06lf\n",a);
    return 0;
}